package io.kelta.runtime.model.system;

import io.kelta.runtime.model.CollectionDefinition;
import io.kelta.runtime.model.FieldDefinition;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Generates {@code docs/authoring/system-collections.md} from {@link SystemCollectionDefinitions#all()}
 * and fails when the committed page differs from the render, so a system collection cannot be added,
 * renamed or re-described without regenerating its reference row.
 *
 * <p>Run with {@code -Dkelta.docs.write=true} to rewrite the page instead of checking it.
 */
@DisplayName("System collections reference page")
class SystemCollectionsReferenceTest {

    private static final String REGENERATE =
            "mvn -f kelta-platform/pom.xml -pl runtime/runtime-core test "
                    + "-Dtest=SystemCollectionsReferenceTest -Dkelta.docs.write=true";

    private static final Path PAGE = Path.of(System.getProperty("basedir", System.getProperty("user.dir")))
            .resolve("../../../docs/authoring/system-collections.md")
            .normalize();

    private static final String TABLE_HEADER =
            "| Name | Display name | Purpose | API path | Tenant-scoped | Read-only | Key fields |";

    @Test
    @DisplayName("The committed page equals the render of SystemCollectionDefinitions.all()")
    void committedPageMatchesRender() throws IOException {
        String rendered = render(SystemCollectionDefinitions.all());

        if (Boolean.getBoolean("kelta.docs.write")) {
            Files.writeString(PAGE, rendered, StandardCharsets.UTF_8);
        }

        assertThat(Files.exists(PAGE))
                .as("%s is missing; regenerate it with: %s", PAGE, REGENERATE)
                .isTrue();
        assertThat(Files.readString(PAGE, StandardCharsets.UTF_8))
                .as("%s is stale; regenerate it with: %s", PAGE, REGENERATE)
                .isEqualTo(rendered);
    }

    @Test
    @DisplayName("The committed page has one table row per system collection")
    void pageHasOneRowPerCollection() throws IOException {
        List<String> lines = Files.readAllLines(PAGE, StandardCharsets.UTF_8);
        int header = lines.indexOf(TABLE_HEADER);
        assertThat(header).as("table header missing from %s; regenerate it with: %s", PAGE, REGENERATE)
                .isNotNegative();

        long rows = lines.stream().skip(header + 2).takeWhile(line -> line.startsWith("|")).count();

        assertThat(rows)
                .as("table rows in %s; regenerate it with: %s", PAGE, REGENERATE)
                .isEqualTo(SystemCollectionDefinitions.all().size());
    }

    @Test
    @DisplayName("Rendering is deterministic")
    void renderIsDeterministic() {
        assertThat(render(SystemCollectionDefinitions.all()))
                .isEqualTo(render(SystemCollectionDefinitions.all()));
    }

    static String render(List<CollectionDefinition> definitions) {
        List<CollectionDefinition> sorted = new ArrayList<>(definitions);
        sorted.sort(Comparator.comparing(CollectionDefinition::name));

        StringBuilder out = new StringBuilder();
        out.append("# System Collections Reference\n\n");
        out.append("<!-- Generated by SystemCollectionsReferenceTest from SystemCollectionDefinitions.all().\n");
        out.append("     Do not edit by hand: change the definition, then run\n");
        out.append("     ").append(REGENERATE).append(" -->\n\n");
        out.append("Every system collection the platform defines — the metadata behind collections, fields, users,\n");
        out.append("security, UI, flows and audit — generated from the runtime's system-collection registry.\n");
        out.append("Each is served like a user collection at its API path (JSON:API, see\n");
        out.append("[JSON:API Conventions](/docs/reference/jsonapi/)), and\n");
        out.append("`GET /api/collections/{name}/schema` describes its fields.\n\n");
        out.append("- **Tenant-scoped** — rows belong to one tenant and are isolated by row-level security.\n");
        out.append("- **Read-only** — the API serves reads only (audit logs, history, platform-written data).\n");
        out.append("- **Key fields** — the display field, then every required field.\n\n");
        out.append(sorted.size()).append(" system collections, sorted by name.\n\n");
        out.append("## Collections\n\n");
        out.append(TABLE_HEADER).append('\n');
        out.append("|---|---|---|---|---|---|---|\n");
        for (CollectionDefinition definition : sorted) {
            out.append("| `").append(definition.name()).append("` | ")
                    .append(cell(definition.displayName())).append(" | ")
                    .append(cell(definition.description())).append(" | ")
                    .append(apiPath(definition)).append(" | ")
                    .append(flag(definition.tenantScoped())).append(" | ")
                    .append(flag(definition.readOnly())).append(" | ")
                    .append(keyFields(definition)).append(" |\n");
        }
        return out.toString();
    }

    private static String apiPath(CollectionDefinition definition) {
        String basePath = definition.apiConfig() == null ? null : definition.apiConfig().basePath();
        return basePath == null || basePath.isBlank() ? "—" : "`" + basePath + "`";
    }

    private static String keyFields(CollectionDefinition definition) {
        List<String> parts = new ArrayList<>();
        String display = definition.displayFieldName();
        if (display != null && !display.isBlank()) {
            parts.add("display `" + display + "`");
        }
        List<String> required = definition.fields().stream()
                .filter(field -> !field.nullable())
                .map(FieldDefinition::name)
                .filter(name -> !name.equals(display))
                .map(name -> "`" + name + "`")
                .toList();
        if (!required.isEmpty()) {
            parts.add("required " + String.join(", ", required));
        }
        return parts.isEmpty() ? "—" : String.join("; ", parts);
    }

    private static String flag(boolean value) {
        return value ? "yes" : "no";
    }

    private static String cell(String text) {
        if (text == null || text.isBlank()) {
            return "—";
        }
        return text.strip()
                .replaceAll("\\s*\\R\\s*", " ")
                .replace("|", "\\|")
                .replace("<", "&lt;");
    }
}
