// Regenerates packages/cli/src/docsgen/authoringDocs.ts from every
// docs/authoring/*.md, builds the cli, then regenerates
// packages/cli/{AGENTS.md,COMMANDS.md} from the built registry.
// Run: npm run gen:docs. Freshness is enforced by
// packages/cli/src/docsgen/docsgen.test.ts.
import { execSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = join(here, '..');
const authoringDir = join(webRoot, '..', 'docs', 'authoring');
const cliRoot = join(webRoot, 'packages', 'cli');
const cliDist = join(cliRoot, 'dist');

// `kelta docs agent` and `kelta docs list` would shadow a doc with either name
const RESERVED_TOPICS = new Set(['agent', 'list']);

const topics = readdirSync(authoringDir)
  .filter((name) => name.endsWith('.md'))
  .map((name) => basename(name, '.md'))
  .sort();
for (const topic of topics) {
  if (RESERVED_TOPICS.has(topic)) {
    throw new Error(`docs/authoring/${topic}.md: "${topic}" is a reserved \`kelta docs\` topic`);
  }
}

const entries = topics
  .map((topic) => {
    const content = readFileSync(join(authoringDir, `${topic}.md`), 'utf-8');
    return `  ${JSON.stringify(topic)}:\n    ${JSON.stringify(content)},`;
  })
  .join('\n');
writeFileSync(
  join(cliRoot, 'src', 'docsgen', 'authoringDocs.ts'),
  `// GENERATED by \`npm run gen:docs\` (kelta-web/scripts/gen-docs.mjs) from docs/authoring/*.md — do not edit by hand.\n` +
    `// prettier-ignore\n` +
    `export const AUTHORING_DOCS: Record<string, string> = {\n${entries}\n};\n`
);
console.log(`Wrote packages/cli/src/docsgen/authoringDocs.ts (${topics.length} topics)`);

execSync('npm run build -w packages/cli', { cwd: webRoot, stdio: 'inherit' });

const { allCommands } = await import(join(cliDist, 'registry', 'registry.js'));
const { buildManifest } = await import(join(cliDist, 'registry', 'manifest.js'));
const { renderAgentsMd, renderCommandsMd } = await import(join(cliDist, 'docsgen', 'render.js'));

writeFileSync(join(cliRoot, 'AGENTS.md'), renderAgentsMd());
writeFileSync(join(cliRoot, 'COMMANDS.md'), renderCommandsMd(buildManifest(allCommands)));
console.log('Wrote packages/cli/AGENTS.md and packages/cli/COMMANDS.md');
